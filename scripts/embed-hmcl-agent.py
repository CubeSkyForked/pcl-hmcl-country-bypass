"""Package our compiled Java agent and embed it into the native proxy."""
import argparse
import hashlib
import io
from pathlib import Path
import zipfile

parser = argparse.ArgumentParser()
parser.add_argument('classes', type=Path)
parser.add_argument('jar', type=Path)
parser.add_argument('header', type=Path)
args = parser.parse_args()
sources = sorted((Path(__file__).resolve().parent.parent / 'java').glob('Hmcl*.java'))
source_hash = hashlib.sha256(''.join(p.name + ':' + hashlib.sha256(p.read_bytes()).hexdigest() + '\n' for p in sources).encode('utf-8')).hexdigest()
manifest = ('Manifest-Version: 1.0\r\n'
            'Premain-Class: hkregion.hmcl.HmclRegionAgent\r\n'
            'Agent-Class: hkregion.hmcl.HmclRegionAgent\r\n'
            'Can-Retransform-Classes: true\r\n\r\n')
buffer = io.BytesIO()
with zipfile.ZipFile(buffer, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
    files = [('META-INF/MANIFEST.MF', manifest.encode('ascii')),
             ('META-INF/LICENSE', (Path(__file__).resolve().parents[1] / 'LICENSE').read_bytes())]
    files += [(p.relative_to(args.classes).as_posix(), p.read_bytes())
              for p in sorted(args.classes.rglob('*.class'))]
    for name, content in files:
        info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        archive.writestr(info, content)
data = buffer.getvalue()
args.jar.write_bytes(data)
digest = hashlib.sha256(data).hexdigest()
lines = ['// Generated by scripts/build-hmcl-agent.ps1.',
         f'// Source SHA256: {source_hash}', '#pragma once',
         f'constexpr WCHAR kHmclAgentHash[] = L"{digest}";',
         f'constexpr char kHmclAgentHashA[] = "{digest}";',
         'constexpr BYTE kHmclAgentPayload[] = {']
lines += ['    ' + ', '.join(f'0x{byte:02x}' for byte in data[i:i + 16]) + ','
          for i in range(0, len(data), 16)]
lines += ['};', '']
args.header.write_text('\n'.join(lines), encoding='utf-8')
print(f'Embedded Java agent: {len(data)} bytes; SHA256 {digest}')
