"""Embed the compiled .NET Framework helper into the single native DLL."""
import argparse
import hashlib
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('assembly', type=Path)
parser.add_argument('header', type=Path)
args = parser.parse_args()
data = args.assembly.read_bytes()
digest = hashlib.sha256(data).hexdigest()
source = Path(__file__).resolve().parent.parent / 'managed/PclDownloadRestore.cs'
source_digest = hashlib.sha256(source.read_bytes()).hexdigest()
lines = ['// Generated by scripts/embed-managed.py; rebuild using scripts/build-managed.ps1.',
         f'// Source SHA256: {source_digest}',
         '#pragma once', f'constexpr WCHAR kManagedPayloadHash[] = L"{digest}";',
         'constexpr BYTE kManagedPayload[] = {']
lines += ['    ' + ', '.join(f'0x{byte:02x}' for byte in data[i:i + 16]) + ','
          for i in range(0, len(data), 16)]
lines += ['};', '']
args.header.write_text('\n'.join(lines), encoding='utf-8')
print(f'Embedded {len(data)} bytes; SHA256 {digest}')
