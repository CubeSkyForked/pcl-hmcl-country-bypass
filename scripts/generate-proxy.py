"""Generate ABI-preserving forwarding thunks for the renameable proxy.

The first 17 ordinals retain version.dll's names. Every ordinal dispatches
against the selected system DLL, so overlapping native ordinals are preserved.
Other named exports get separate ordinals; API calls resolve by their name.
"""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--output', required=True, type=Path)
parser.add_argument('--architecture', choices=['x64', 'x86'], required=True)
parser.add_argument('--assembler', choices=['gas', 'masm'], default='gas')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
libraries = json.loads((root / 'src/proxy_exports.json').read_text())['libraries']
ordinal_count = max(e['ordinal'] for lib in libraries.values() for e in lib['exports'])
version = {e['ordinal']: e['name'] for e in libraries['version']['exports']}
version_names = set(version.values())
other_names = sorted({e['name'] for lib in libraries.values() for e in lib['exports'] if e['name']} - version_names)
assert ordinal_count < 256
specs = [(None, ordinal) for ordinal in range(1, ordinal_count + 1)]
specs += [(name, 0) for name in other_names]
out = args.output
out.mkdir(parents=True, exist_ok=True)

def write(name, content):
    target = out / name
    if not target.exists() or target.read_text(encoding='utf-8') != content:
        target.write_text(content, encoding='utf-8')

header = ['// Generated by scripts/generate-proxy.py.', '#pragma once',
          f'constexpr unsigned kForwardCount = {len(specs)};',
          'struct ForwardSpec { const char* name; WORD ordinal; };',
          'constexpr ForwardSpec kForwardSpecs[] = {']
header += [f'    {{{json.dumps(name) if name else "nullptr"}, {ordinal}}},' for name, ordinal in specs]
header += ['};']
write('proxy_exports.h', '\n'.join(header) + '\n')

exports = ['LIBRARY HKRegionProxy', 'EXPORTS']
prefix = '_' if args.architecture == 'x86' and args.assembler == 'masm' else ''
for ordinal in range(1, ordinal_count + 1):
    name = version.get(ordinal)
    # LINK adds the x86 cdecl underscore itself for undecorated .def targets.
    exports.append(f'    {name or "Ordinal_" + str(ordinal)}=HKR_Thunk_{ordinal - 1} @{ordinal}' + ('' if name else ' NONAME'))
for index, name in enumerate(other_names, ordinal_count):
    exports.append(f'    {name}=HKR_Thunk_{index} @{256 + index - ordinal_count}')
for ordinal, name, size in [(4096, 'HKRegion_Install', 4), (4097, 'HKRegion_GetInitializationStatus', 0), (4098, 'HKRegion_WaitForInitialization', 4), (4099, 'HKRegion_GetManagedPatchStatus', 0), (4100, 'HKRegion_ExtractHmclAgentW', 16)]:
    decoration = f'@{size}' if args.architecture == 'x86' else ''
    exports.append(f'    {name}={prefix}{name}{decoration} @{ordinal}')
write('proxy.def', '\n'.join(exports) + '\n')

is64 = args.architecture == 'x64'
masm = args.assembler == 'masm'
symbol_prefix = '' if is64 else '_'
resolver = symbol_prefix + 'HKR_ResolveForwarder'
if masm:
    asm = ([] if is64 else ['.686p', '.xmm', '.model flat'])
    asm += [f'EXTERN {resolver}:PROC', '.code']
else:
    asm = ['.intel_syntax noprefix', '.text', f'.extern {resolver}']

for index in range(len(specs)):
    name = symbol_prefix + f'HKR_Thunk_{index}'
    if masm:
        asm += [f'PUBLIC {name}', f'{name} PROC' + (' FRAME' if is64 else '')]
    else:
        asm += ['.p2align 4', f'.globl {name}']
        if is64:
            asm += [f'.seh_proc {name}']
        asm += [f'{name}:']
    if is64:
        # 32 bytes of shadow space, integer arguments, XMM0..3, and alignment.
        asm += ['    sub rsp, 168', '    .allocstack 168' if masm else '    .seh_stackalloc 168',
                '    .endprolog' if masm else '    .seh_endprologue']
        for offset, register in [(32, 'rcx'), (40, 'rdx'), (48, 'r8'), (56, 'r9')]:
            asm += [f'    mov [rsp+{offset}], {register}']
        for i in range(4):
            asm += [f'    movdqu [rsp+{64 + i * 16}], xmm{i}']
        asm += [f'    mov ecx, {index}', f'    call {resolver}', '    mov r11, rax']
        for offset, register in [(32, 'rcx'), (40, 'rdx'), (48, 'r8'), (56, 'r9')]:
            asm += [f'    mov {register}, [rsp+{offset}]']
        for i in range(4):
            asm += [f'    movdqu xmm{i}, [rsp+{64 + i * 16}]']
        asm += ['    add rsp, 168', '    jmp r11']
    else:
        # Leave stdcall arguments and the caller's return address untouched.
        asm += ['    push ecx', '    push edx', f'    push {index}', f'    call {resolver}',
                '    add esp, 4', '    pop edx', '    pop ecx', '    jmp eax']
    if masm:
        asm += [f'{name} ENDP']
    elif is64:
        asm += ['.seh_endproc']
if masm:
    asm += ['END']
write('proxy_thunks.asm' if masm else 'proxy_thunks.S', '\n'.join(asm) + '\n')
